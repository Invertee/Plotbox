def text_outline_paths(
    text: str,
    *,
    x: float,
    baseline_y: float,
    font_size: float,
    prefix: str,
) -> list[DesignPath]:
    cell = font_size / 7
    cursor = x
    result: list[DesignPath] = []
    for character_index, character in enumerate(text.upper()):
        if character.isspace():
            cursor += cell * 4
            continue
        pattern = GLYPHS.get(
            character,
            ("11111", "10001", "00110", "00100", "00000", "00100", "00000"),
        )
        for row, values in enumerate(pattern):
            for column, value in enumerate(values):
                if value != "1":
                    continue
                left = cursor + column * cell
                top = baseline_y - font_size + row * cell
                right = left + cell
                bottom = top + cell
                result.append(
                    DesignPath(
                        path_id=f"{prefix}-glyph-{character_index + 1}-cell-{row + 1}-{column + 1}",
                        commands=[
                            MoveCommand(point=Point(x=left, y=top)),
                            LineCommand(point=Point(x=right, y=top)),
                            LineCommand(point=Point(x=right, y=bottom)),
                            LineCommand(point=Point(x=left, y=bottom)),
                            LineCommand(point=Point(x=left, y=top)),
                            CloseCommand(),
                        ],
                        closed=True,
                        metadata={"fixture_font": "plotter-5x7-v1", "character": character},
                    )
                )
        cursor += cell * 6
    return result
